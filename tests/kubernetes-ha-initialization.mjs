import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {inicializarControlPlaneHA} from '../laboratorios/kubernetes-real/debian/inicializacion-ha.mjs';
const calls=[];
const access={fresh:true,background:async(...args)=>{calls.push({type:'background',args});},execute:async(...args)=>{calls.push({type:'execute',args});}};
await inicializarControlPlaneHA(access);
assert.equal(calls.length,4);
assert.match(calls[0].args[2],/phase certs all/);
assert.match(calls[0].args[2],/phase etcd local/);
assert.match(calls[0].args[2],/phase control-plane apiserver/);
assert.doesNotMatch(calls[0].args[2],/control-plane (scheduler|controller-manager)/);
assert.match(calls[1].args[2],/super-admin.conf/);
assert.match(calls[1].args[2],/--cacert \/etc\/kubernetes\/pki\/ca.crt/);
assert.match(calls[1].args[2],/\/readyz/);
assert.match(calls[1].args[2],/trap .*rmdir/);
assert.doesNotMatch(calls[1].args[2],/insecure|--skip|curl -k/);
assert.match(calls[2].args[2],/phase control-plane controller-manager/);
assert.match(calls[2].args[2],/phase control-plane scheduler/);
assert.match(calls[3].args[2],/--upload-certs/);
assert.match(calls[3].args[2],/--skip-phases=preflight,certs,kubeconfig,etcd,control-plane,kubelet-start/);
assert.doesNotMatch(calls[3].args[2],/skip-phases=[^ ]*(wait-control-plane|bootstrap-token|upload-config)/);
const bash=process.platform==='win32'?'C:/Program Files/Git/bin/bash.exe':'bash';
for(const call of calls){assert.ok(call.args[2].length<2500);const check=spawnSync(bash,['--noprofile','--norc','-n'],{input:call.args[2],encoding:'utf8'});assert.equal(check.status,0,check.stderr);}
let touched=false;
await assert.rejects(inicializarControlPlaneHA({...access,fresh:false,background:()=>{touched=true;}}),/máquina nueva/);assert.equal(touched,false);
const failure=Error('API todavía no responde');let backgroundCalls=0;
await assert.rejects(inicializarControlPlaneHA({...access,background:async()=>{backgroundCalls++;},execute:async()=>{throw failure;}}),error=>error===failure);assert.equal(backgroundCalls,1,'No se arrancan controladores ni se continúa init si falla la API');
let readyChecked=false;
await assert.rejects(inicializarControlPlaneHA({...access,background:async()=>{throw failure;},execute:async()=>{readyChecked=true;}}),error=>error===failure);assert.equal(readyChecked,false);
console.log('HA: fases nativas antes de controladores, espera HTTPS autenticada con limpieza temporal, conserva healthchecks y falla sin continuar ni tocar guardados.');
